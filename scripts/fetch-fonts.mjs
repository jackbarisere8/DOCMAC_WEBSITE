#!/usr/bin/env node
/**
 * Download the Docmac webfonts from Google Fonts and generate a self-hosted
 * assets/fonts.css. Run this only when the font families or weights change.
 *
 * Usage: node scripts/fetch-fonts.mjs
 */

import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const FONT_DIR = path.join(ROOT, 'assets', 'fonts');
const CSS_PATH = path.join(ROOT, 'assets', 'fonts.css');

const CSS_URL =
  'https://fonts.googleapis.com/css2?' +
  [
    'family=Plus+Jakarta+Sans:ital,wght@0,400..800;1,500..700',
    'family=DM+Mono:wght@400;500',
    'display=swap',
  ].join('&');

const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

// DM Mono is only used for small labels, so the latin subset is enough.
const SUBSETS = {
  'Plus Jakarta Sans': new Set(['latin', 'latin-ext']),
  'DM Mono': new Set(['latin']),
};

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

async function main() {
  const css = await fetch(CSS_URL, { headers: { 'User-Agent': USER_AGENT } }).then((res) => {
    if (!res.ok) throw new Error(`Google Fonts responded ${res.status}`);
    return res.text();
  });

  await fsp.mkdir(FONT_DIR, { recursive: true });

  const blocks = [];
  const pattern = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  let match;
  while ((match = pattern.exec(css))) {
    const subset = match[1];
    const body = match[2];
    const family = body.match(/font-family:\s*'([^']+)'/)?.[1];
    const style = body.match(/font-style:\s*([^;]+);/)?.[1]?.trim() || 'normal';
    const weight = body.match(/font-weight:\s*([^;]+);/)?.[1]?.trim() || '400';
    const url = body.match(/url\((https:\/\/[^)]+)\)/)?.[1];
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
    if (!family || !url || !SUBSETS[family]?.has(subset)) continue;

    const extension = '.woff2';
    const fileName = `${slugify(family)}-${slugify(style)}-${slugify(weight)}-${subset}${extension}`;
    const destination = path.join(FONT_DIR, fileName);

    const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
    if (!response.ok) throw new Error(`Could not download ${url}: ${response.status}`);
    const buffer = Buffer.from(await response.arrayBuffer());
    await fsp.writeFile(destination, buffer);
    console.log(`saved ${fileName} (${(buffer.length / 1024).toFixed(1)} KB)`);

    blocks.push({ family, style, weight, fileName, range, bytes: buffer.length });
  }

  if (!blocks.length) throw new Error('No font faces were parsed.');

  const rules = blocks
    .map(
      (block) => `@font-face {
  font-family: '${block.family}';
  font-style: ${block.style};
  font-weight: ${block.weight};
  font-display: swap;
  src: url('fonts/${block.fileName}') format('woff2');
  unicode-range: ${block.range};
}`,
    )
    .join('\n\n');

  await fsp.writeFile(
    CSS_PATH,
    `/* Self-hosted fonts. Generated by scripts/fetch-fonts.mjs. */\n\n${rules}\n`,
  );

  const total = blocks.reduce((sum, block) => sum + block.bytes, 0);
  console.log(`\nWrote ${path.relative(ROOT, CSS_PATH)} with ${blocks.length} faces (${(total / 1024).toFixed(1)} KB total).`);
}

main().catch((error) => {
  console.error('Font download failed:', error);
  process.exitCode = 1;
});
